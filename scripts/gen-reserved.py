#!/usr/bin/env python3
"""Regenerate dts/haydn-reserved.dtsi from the phone's own live FDT.

Usage:
    scripts/gen-reserved.py haydn-fdt.dts > dts/haydn-reserved.dtsi

The input is the decompiled form of /sys/firmware/fdt:

    adb shell su -c "cat /sys/firmware/fdt" > haydn-fdt.dtb
    dtc -I dtb -O dts -o haydn-fdt.dts haydn-fdt.dtb

Every range in the output carries its source node name, so a reader can find
the line in haydn-fdt.dts that produced it.
"""

import re
import sys


def find_block(text, keyword):
    """Return the brace-balanced body that follows `keyword`."""
    start = text.find(keyword)
    if start < 0:
        raise SystemExit(f'{keyword}: not in the tree')
    i = text.find('{', start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[start:j + 1]
    raise SystemExit(f'{keyword}: unbalanced')


def regions(block):
    """Yield (name, address, size, no_map, compatible) for each node with a reg."""
    for m in re.finditer(r'([\w\-@]+)\s*\{([^{}]*)\}', block):
        name, body = m.group(1), m.group(2)
        reg = re.search(r'reg\s*=\s*<([^>]*)>', body)
        if not reg:
            continue
        cells = [int(c, 16) for c in reg.group(1).split()]
        if len(cells) < 4:
            continue
        address = cells[0] * 0x100000000 + cells[1]
        size = cells[2] * 0x100000000 + cells[3]
        if size == 0:
            continue
        compat = re.search(r'compatible\s*=\s*"([^"]+)"', body)
        yield name, address, size, 'no-map' in body, compat.group(1) if compat else None


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding='utf-8', errors='replace') as f:
        text = f.read()
    block = find_block(text, 'reserved-memory')
    out = [
        '// Generated by scripts/gen-reserved.py from the phone\'s live FDT.',
        '// Do not edit by hand. See docs/hardware.md for the source of each range.',
        '/ {',
        '    reserved-memory {',
        '        #address-cells = <2>;',
        '        #size-cells = <2>;',
        '        ranges;',
    ]
    count = 0
    for name, address, size, no_map, compat in regions(block):
        node = name.split('@')[0]
        out.append('')
        out.append(f'        {node}@0x{address:x} {{')
        if compat:
            out.append(f'            compatible = "{compat}";')
        if no_map:
            out.append('            no-map;')
        out.append(f'            reg = <0x0 0x{address:x} 0x0 0x{size:x}>;')
        out.append('        };')
        count += 1
    out += ['    };', '};', '']
    sys.stdout.write('\n'.join(out))
    print(f'/* {count} regions */', file=sys.stderr)


if __name__ == '__main__':
    main()
