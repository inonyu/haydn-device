#!/usr/bin/env python3
"""Regenerate dts/haydn-reserved.dtsi from the phone's live FDT blob.

gen-reserved.py reads a DTS, which needs dtc to have produced it. This reads
the FDT binary itself, so the chain is one step shorter and does not depend on
dtc being installed:

    adb shell su -c "cat /sys/firmware/fdt" > haydn-fdt.dtb
    scripts/gen-reserved-live.py haydn-fdt.dtb > dts/haydn-reserved.dtsi

The output is the same shape gen-reserved.py produces, so the two can be
diffed against each other -- and they are: tests/reserved-live.py does it.
"""

import struct
import sys

FDT_MAGIC = 0xd00dfeed
FDT_BEGIN_NODE = 1
FDT_END_NODE = 2
FDT_PROP = 3
FDT_NOP = 4
FDT_END = 9


def parse(blob):
    """Yield (path tuple, {prop: bytes}) for every node, in file order."""
    magic, totalsize, off_struct, off_strings = struct.unpack_from('>IIII', blob, 0)
    if magic != FDT_MAGIC:
        raise SystemExit('not an FDT: magic 0x%08x' % magic)
    strings = blob[off_strings:totalsize]

    def string_at(off):
        end = strings.index(b'\0', off)
        return strings[off:end].decode('utf-8', 'replace')

    stack = []
    at = off_struct
    node = None
    while at < off_strings:
        token = struct.unpack_from('>I', blob, at)[0]
        if token == FDT_BEGIN_NODE:
            at += 4
            end = blob.index(b'\0', at)
            name = blob[at:end].decode('utf-8', 'replace') or '/'
            stack.append(name)
            node = (tuple(stack), {})
            yield node
            at = (end + 4) & ~3
        elif token == FDT_END_NODE:
            stack.pop()
            at += 4
        elif token == FDT_PROP:
            length, nameoff = struct.unpack_from('>II', blob, at + 4)
            value = blob[at + 12:at + 12 + length]
            if node is not None:
                node[1][string_at(nameoff)] = value
            at = (at + 12 + length + 3) & ~3
        elif token == FDT_NOP:
            at += 4
        elif token == FDT_END:
            break
        else:
            raise SystemExit('unknown FDT token %d at 0x%x' % (token, at))


def cells(value):
    return [struct.unpack_from('>I', value, i)[0] for i in range(0, len(value) - len(value) % 4, 4)]


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__.strip())

    blob = open(sys.argv[1], 'rb').read()
    nodes = list(parse(blob))

    rm = next((n for n in nodes if n[0][-1] == 'reserved-memory'), None)
    if rm is None:
        raise SystemExit('the blob has no reserved-memory node')

    depth = len(rm[0])
    ac = cells(rm[1]['#address-cells'])[0] if '#address-cells' in rm[1] else 2
    sc = cells(rm[1]['#size-cells'])[0] if '#size-cells' in rm[1] else 2

    regions = []
    for path, props in nodes:
        if len(path) != depth + 1 or path[:-1] != rm[0]:
            continue
        if 'reg' not in props:
            continue
        values = cells(props['reg'])
        if len(values) < ac + sc:
            # Some regions carry a short reg (a placeholder the bootloader
            # fills in later). They are not ranges this tree can describe.
            continue
        addr = 0
        for i in range(ac):
            addr = (addr << 32) | values[i]
        size = 0
        for i in range(sc):
            size = (size << 32) | values[ac + i]
        if size == 0:
            continue
        regions.append((path[-1], addr, size, 'no-map' in props))

    regions.sort(key=lambda r: r[1])

    total = sum(r[2] for r in regions)
    print('// Generated by scripts/gen-reserved-live.py from the phone\'s own FDT.')
    print('//')
    print('// %d regions, %.1f MiB. Do not edit: change the input and regenerate.' % (len(regions), total / 1048576.0))
    print('//')
    print('// The generator the earlier version of this file used read a DTS, which')
    print('// needs dtc. This reads the FDT binary, so the chain is one step shorter:')
    print('//')
    print('//     adb shell su -c "cat /sys/firmware/fdt" > haydn-fdt.dtb')
    print('//     scripts/gen-reserved-live.py haydn-fdt.dtb > dts/haydn-reserved.dtsi')
    print('/ {')
    print('    reserved-memory {')
    for name, addr, size, no_map in regions:
        base = name.split('@')[0]
        print('        %s@0x%x {' % (base, addr))
        if no_map:
            print('            no-map;')
        print('            reg = <0x%x 0x%x 0x%x 0x%x>;' % (
            addr >> 32, addr & 0xffffffff, size >> 32, size & 0xffffffff))
        print('        };')
    print('    };')
    print('};')


if __name__ == '__main__':
    main()
